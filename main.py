item1 = 'Phone'
item1_price = 100
item1_quantity = 5
item1_price_total = item1_price * item1_quantity

print(type(item1 = 'Phone'))
print(type(item1_price = 100))
print(type(item1_quantity = 5))
print(type(item1_price_total = item1_price * item1_quantity))

# outputs <class 'dtype'>
# this is because each datatype is an instace of str/obj
# each dtype is an obj that has been instantiated by some class

